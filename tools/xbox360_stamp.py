"""Writes the Xbox 360 build's stamp header (port/xbox360/build.py): the
version, commits (this repository's, then the game's) and build time the
XEX logs on its first line, so a test can tell which build ran (a failed
upload to the console leaves the old one).

usage: xbox360_stamp.py OUTPUT
"""

import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

# this repository, and the game in it (the chupathingyce submodule)
HERE = Path(__file__).resolve().parent.parent
GAME = HERE / "chupathingyce"
sys.path.insert(0, str(GAME))
from tools.version import version  # noqa: E402


def commit(root: Path) -> str:
    def git(*arguments: str) -> str:
        result = subprocess.run(["git", "-C", str(root), *arguments], capture_output=True, text=True)
        return result.stdout.strip() if result.returncode == 0 else ""

    head = git("rev-parse", "--short=9", "HEAD") or "unknown"
    return head + ("-dirty" if git("status", "--porcelain", "--untracked-files=no", "--ignore-submodules") else "")


def main() -> None:
    output = Path(sys.argv[1])
    built = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    text = (
        "/* generated by tools/xbox360_stamp.py */\n"
        f'#define XBOX360_BUILD_VERSION "{version()}"\n'
        f'#define XBOX360_BUILD_COMMIT "{commit(HERE)} (game {commit(GAME)})"\n'
        f'#define XBOX360_BUILD_TIME "{built}"\n'
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
